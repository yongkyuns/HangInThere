    private fun simplify(points: List<Point2D>, tolerance: Double = 1.0) =
        BarFitter.simplify(points, tolerance) {}

    @Test fun exactObliqueThresholdDoesNotAcquireARoundingEpsilon() {
        // Cross-product distance is exactly one pixel, including a projection
        // whose decimal coordinates are not representable as binary doubles.
        val points = listOf(Point2D(0.0, 0.0), Point2D(2.0, 1.0), Point2D(6.0, 8.0))
        for (sx in listOf(-1, 1)) for (sy in listOf(-1, 1)) {
            val input = points.map { Point2D(100 + sx * it.x, 100 + sy * it.y) }
            assertEquals(listOf(input.first(), input.last()), simplify(input))
        }
        assertEquals(points, simplify(points, .999999))
    }

    @Test fun equalDeviationsKeepTheFirstObservedVertex() {
        val points = listOf(Point2D(0.0, 0.0), Point2D(3.0, 2.0), Point2D(7.0, 2.0), Point2D(10.0, 0.0))
        assertEquals(listOf(points[0], points[1], points[3]), simplify(points, 1.5))
        assertEquals(listOf(points[3], points[2], points[0]), simplify(points.reversed(), 1.5))
    }

    @Test fun finiteEndpointAndExistingShortSegmentFallbackRemainDistinct() {
        val outside = listOf(Point2D(0.0, 0.0), Point2D(20.0, .5), Point2D(10.0, 0.0))
        assertEquals(outside, simplify(outside))
        val short = listOf(Point2D(0.0, 0.0), Point2D(1.1, 0.0), Point2D(1.0, 0.0))
        assertEquals(short, simplify(short))
        assertEquals(emptyList(), simplify(emptyList()))
        assertEquals(short.take(2), simplify(short.take(2)))
    }

    @Test fun overflowingIntermediateGeometryIsRejectedExplicitly() {
        for (scale in listOf(1e100, 1e200)) {
            val error = assertFailsWith<BarFitException> {
                simplify(listOf(Point2D(0.0, 0.0), Point2D(2 * scale, scale), Point2D(6 * scale, 8 * scale)))
            }
            assertEquals("invalidContour", error.message)
        }
    }
